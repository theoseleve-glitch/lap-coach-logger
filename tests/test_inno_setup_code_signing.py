"""T179: Inno Setup script wired for code signing.

Code signing protects users from "Unknown Publisher" Windows
SmartScreen warnings on the installer and uninstaller. The
``.iss`` script declares *what* gets signed; the build
pipeline registers the actual signtool (with cert path and
password) at compile time via ``iscc /Ssigntool="..."``.

T179 pins two declarative properties of the .iss:

1. ``SignTool=signtool`` in ``[Setup]`` — tells Inno to invoke
   the previously-registered ``signtool`` command on the
   built installer.
2. ``SignedUninstaller=yes`` in ``[Setup]`` — also sign the
   uninstaller, otherwise users see two different SmartScreen
   warnings depending on whether they're installing or
   removing.

The actual cert is not checked in. Build pipelines provide it
via ``iscc /Ssigntool="signtool.exe sign /f cert.pfx /p $env:CERT_PW $f"``
or similar. For alpha builds, a self-signed cert generated by
``New-SelfSignedCertificate`` is acceptable.

Source-content pin (consistent with T175-T178).
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

_ISS_PATH = (
    Path(__file__).resolve().parents[1]
    / "installer" / "LapCoachLogger.iss"
)


@pytest.fixture(scope="module")
def iss_text() -> str:
    return _ISS_PATH.read_text(encoding="utf-8")


def _setup_section(iss_text: str) -> str:
    """Slice the [Setup] section body — anchored from `[Setup]`
    to the next `[Section]` header."""
    match = re.search(
        r'\[Setup\]([\s\S]*?)(?=\n\[\w+\]|\Z)',
        iss_text,
    )
    assert match is not None, ".iss must have a [Setup] section"
    return match.group(1)


def test_iss_declares_sign_tool(iss_text: str) -> None:
    """``SignTool=signtool`` declares the installer should be
    signed using a previously-registered tool named
    ``signtool``."""
    setup_body = _setup_section(iss_text)
    assert re.search(
        r'^\s*SignTool\s*=\s*signtool\b',
        setup_body,
        re.MULTILINE,
    ), (
        "[Setup] must declare `SignTool=signtool` so iscc "
        "invokes the registered signing tool on the installer"
    )


def test_iss_declares_signed_uninstaller(iss_text: str) -> None:
    """``SignedUninstaller=yes`` ensures the uninstaller is
    also signed. Without it, removal triggers a different
    SmartScreen warning than install."""
    setup_body = _setup_section(iss_text)
    assert re.search(
        r'^\s*SignedUninstaller\s*=\s*yes\b',
        setup_body,
        re.MULTILINE | re.IGNORECASE,
    ), (
        "[Setup] must declare `SignedUninstaller=yes` so the "
        "uninstaller carries the same signature as the installer"
    )


def test_iss_documents_signtool_registration(iss_text: str) -> None:
    """The .iss must document how to register the signtool at
    compile time — otherwise contributors will hit cryptic Inno
    errors when running the build without the registration.
    Tolerant: any comment mentioning ``iscc`` and ``signtool``
    proves the docs are present."""
    # Match a single-line `;` comment that mentions both iscc
    # and Signtool / signtool argument flag.
    assert re.search(
        r';.*iscc.*signtool|;.*signtool.*iscc',
        iss_text,
        re.IGNORECASE,
    ), (
        ".iss must include a comment documenting how to "
        "register the signtool at compile time "
        "(e.g. `; iscc /Ssigntool=\"...\"`)"
    )
