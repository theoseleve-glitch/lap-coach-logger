"""Generate Windows VERSIONINFO resource from app_identity.VERSION.

Keeps build/windows/version_info.txt in sync with the canonical version
constant. Checked-in copies drift on every bump; generating it at build
time is the simplest way to guarantee they match.

Run from repo root:

    python scripts/gen_version_info.py

Output is deterministic given the same VERSION and companyName, so CI
can diff it against a checked-in reference if desired.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from lap_coach_logger.app_identity import APP_NAME, COMPANY_NAME, VERSION  # noqa: E402


_TEMPLATE = """# UTF-8
# PyInstaller version resource — GENERATED by scripts/gen_version_info.py
# Do not edit by hand. Source: src/lap_coach_logger/app_identity.py
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vers_tuple},
    prodvers={vers_tuple},
    mask=0x3F,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [
            StringStruct('CompanyName', '{company}'),
            StringStruct('FileDescription', 'Local telemetry logger for sim racing'),
            StringStruct('FileVersion', '{vers_dotted}'),
            StringStruct('InternalName', 'LapCoachLogger'),
            StringStruct('LegalCopyright', 'Copyright (c) 2026 {company}'),
            StringStruct('OriginalFilename', 'LapCoachLogger.exe'),
            StringStruct('ProductName', '{product}'),
            StringStruct('ProductVersion', '{vers_dotted}')
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def _parse_version(version: str) -> tuple[int, int, int, int]:
    """Parse ``"2.0.0"`` → ``(2, 0, 0, 0)``.

    PyInstaller's VERSIONINFO wants exactly 4 ints. We pad trailing zeros
    and reject any pre-release suffix (``rc1``, ``dev``, etc.) because
    those cannot be encoded in the numeric tuple — mix them into the
    installer filename instead.
    """
    core = version.strip()
    parts = core.split(".")
    if any(not p.isdigit() for p in parts):
        raise ValueError(
            f"VERSION {version!r} contains non-numeric segments. "
            "PyInstaller VERSIONINFO only supports integer tuples — "
            "encode pre-release tags in the artifact filename instead."
        )
    ints = [int(p) for p in parts]
    while len(ints) < 4:
        ints.append(0)
    if len(ints) > 4:
        raise ValueError(f"VERSION {version!r} has more than 4 components")
    return tuple(ints)  # type: ignore[return-value]


def main() -> int:
    out_path = REPO_ROOT / "build" / "windows" / "version_info.txt"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    vers_tuple = _parse_version(VERSION)
    content = _TEMPLATE.format(
        vers_tuple=repr(vers_tuple),
        vers_dotted=".".join(str(i) for i in vers_tuple),
        company=COMPANY_NAME,
        product=APP_NAME,
    )
    out_path.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {out_path} (version {VERSION})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
