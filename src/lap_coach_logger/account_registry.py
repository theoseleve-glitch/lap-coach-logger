"""Account registry — tracks known Clerk accounts + the active one.

ADR-011 (Q63) commits to "1 user = 1 DriverProfile" for v1, but the
overall design supports multiple accounts later. The OS keychain
holds account-keyed entries (``TokenStore`` in T050) but does not
enumerate them. This registry is the missing book-keeper: it
records which accounts have been paired and which one is currently
active, persisted as JSON under ``config_dir()`` so the wiring layer
can re-instantiate ``PairingViewModel(known_account=...)`` on next
launch.

Single-account is the only M1 path that's user-facing — adding a
second account works mechanically but no UI invokes it. Keeping
the surface multi-aware now means a future account picker doesn't
require a refactor.

Persistence shape::

    {
      "active":   "alice@example.com" | null,
      "accounts": ["alice@example.com", "bob@example.com"]
    }

Corrupt state files are treated as a cold start, not as fatal,
because the keychain is the source of truth for *credentials* —
losing the registry just means the user has to pair again.
"""

from __future__ import annotations

import json
from pathlib import Path


class AccountRegistry:
    """File-backed list of known accounts plus an active-account pointer.

    All write operations flush synchronously: the registry is small
    (one user-name string + a tiny list) and the cost of a partial
    write is much higher than the cost of a redundant one.
    """

    def __init__(self, *, state_path: Path) -> None:
        self._state_path = state_path
        self._accounts: list[str] = []
        self._active: str | None = None
        self._load()

    # ------------------------------------------------------------------
    # Read-only views
    # ------------------------------------------------------------------

    @property
    def accounts(self) -> tuple[str, ...]:
        """Insertion-ordered tuple of every known account."""
        return tuple(self._accounts)

    @property
    def active_account(self) -> str | None:
        """The currently-active account, or ``None`` if none is selected."""
        return self._active

    # ------------------------------------------------------------------
    # Mutations
    # ------------------------------------------------------------------

    def add_account(self, account: str) -> None:
        """Record a new account. First add becomes active automatically."""
        name = self._normalize(account)
        if name in self._accounts:
            return
        self._accounts.append(name)
        if self._active is None:
            self._active = name
        self._save()

    def set_active(self, account: str) -> None:
        """Promote a known account to active. Raises on unknown names."""
        name = self._normalize(account)
        if name not in self._accounts:
            raise ValueError(
                f"unknown account {account!r}; add_account it first"
            )
        if self._active != name:
            self._active = name
            self._save()

    def remove_account(self, account: str) -> None:
        """Drop an account. If it was active, fall back to the first remaining."""
        name = account.strip() if account else ""
        if name not in self._accounts:
            return
        self._accounts.remove(name)
        if self._active == name:
            self._active = self._accounts[0] if self._accounts else None
        self._save()

    def clear(self) -> None:
        """Wipe the registry — used on full sign-out."""
        if not self._accounts and self._active is None:
            return
        self._accounts = []
        self._active = None
        self._save()

    # ------------------------------------------------------------------
    # internals
    # ------------------------------------------------------------------

    @staticmethod
    def _normalize(account: str) -> str:
        if account is None or not account.strip():
            raise ValueError("account name must be non-empty")
        return account.strip()

    def _load(self) -> None:
        if not self._state_path.exists():
            return
        try:
            payload = json.loads(self._state_path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, UnicodeDecodeError, OSError):
            # Corrupt or unreadable: treat as cold start. The keychain
            # is the source of truth for credentials; the registry can
            # be regenerated by re-pairing.
            return
        if not isinstance(payload, dict):
            return
        raw_accounts = payload.get("accounts")
        if isinstance(raw_accounts, list):
            self._accounts = [str(a) for a in raw_accounts if isinstance(a, str)]
        active = payload.get("active")
        if isinstance(active, str) and active in self._accounts:
            self._active = active

    def _save(self) -> None:
        self._state_path.parent.mkdir(parents=True, exist_ok=True)
        payload = {"active": self._active, "accounts": list(self._accounts)}
        self._state_path.write_text(
            json.dumps(payload, indent=2), encoding="utf-8"
        )


__all__ = ["AccountRegistry"]
